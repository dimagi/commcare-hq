"""
Report on quarterly and yearly invoicing, to support removing them.

``BillingAccount.invoicing_plan`` (see :class:`InvoicingPlan`) only has an
effect on customer billing accounts: it widens the billing period of the
customer invoices generated by
:func:`corehq.apps.accounting.tasks.generate_invoices_based_on_date` and
changes how customer invoice line items are quantified and priced.

The field carries no history, so "has quarterly or yearly invoicing ever been
used?" is answered from two independent angles:

* accounts *currently* set to ``QUARTERLY`` or ``YEARLY``, and
* customer invoices whose billing period spans more than one calendar month,
  which is durable evidence that a non-monthly plan was in effect when the
  invoice was generated, even if the account has since been set back to
  ``MONTHLY``.
"""
import csv
from collections import defaultdict

from django.core.management.base import BaseCommand
from django.db.models import (
    Count,
    ExpressionWrapper,
    IntegerField,
    Max,
    Q,
)
from django.db.models.functions import ExtractMonth, ExtractYear

from corehq.apps.accounting.models import (
    BillingAccount,
    CustomerInvoice,
    Invoice,
    InvoicingPlan,
    Subscription,
)

#: Number of calendar months an invoice's billing period touches. A monthly
#: invoice covers exactly one; anything wider was generated under a quarterly
#: or yearly invoicing plan.
MONTHS_SPANNED = ExpressionWrapper(
    (ExtractYear('date_end') - ExtractYear('date_start')) * 12
    + (ExtractMonth('date_end') - ExtractMonth('date_start'))
    + 1,
    output_field=IntegerField(),
)


def get_non_monthly_accounts():
    """Accounts currently configured for quarterly or yearly invoicing."""
    return BillingAccount.objects.exclude(
        invoicing_plan=InvoicingPlan.MONTHLY
    ).order_by('name')


def get_multi_month_invoices(queryset):
    """
    Filter ``queryset`` down to invoices billing more than one calendar month.

    ``queryset`` may be of :class:`Invoice` or :class:`CustomerInvoice`.
    """
    return queryset.annotate(months_spanned=MONTHS_SPANNED).filter(
        months_spanned__gt=1
    )


def get_subscription_stats(account_ids):
    """
    Map account id to subscription counts for the given accounts.

    Includes subscriptions hidden to ops, so that nothing is missed.
    """
    rows = (
        Subscription.visible_and_suppressed_objects
        .filter(account_id__in=account_ids)
        .values('account_id')
        .annotate(
            subscriptions=Count('id'),
            active=Count('id', filter=Q(is_active=True)),
            open_ended=Count('id', filter=Q(date_end__isnull=True)),
            latest_end=Max('date_end'),
        )
    )
    return {row['account_id']: row for row in rows}


def get_customer_invoice_stats(account_ids):
    """Map account id to customer invoice counts for the given accounts."""
    rows = (
        CustomerInvoice.api_objects
        .filter(account_id__in=account_ids)
        .values('account_id')
        .annotate(invoices=Count('id'), latest_end=Max('date_end'))
    )
    return {row['account_id']: row for row in rows}


def group_multi_month_customer_invoices():
    """Map account id to its customer invoices that bill multiple months."""
    invoices = defaultdict(list)
    multi_month = get_multi_month_invoices(CustomerInvoice.api_objects.all())
    for invoice in multi_month.order_by('account_id', 'date_start'):
        invoices[invoice.account_id].append(invoice)
    return invoices


def print_table(stdout, headers, rows):
    if not rows:
        stdout.write("  (none)\n")
        return
    str_rows = [['' if value is None else str(value) for value in row] for row in rows]
    widths = [
        max(len(header), *(len(row[i]) for row in str_rows))
        for i, header in enumerate(headers)
    ]
    template = '  '.join('{:<%d}' % width for width in widths)
    stdout.write('  ' + template.format(*headers).rstrip() + '\n')
    stdout.write('  ' + template.format(*('-' * width for width in widths)).rstrip() + '\n')
    for row in str_rows:
        stdout.write('  ' + template.format(*row).rstrip() + '\n')


ACCOUNT_HEADERS = [
    'Account ID',
    'Name',
    'Invoicing plan',
    'Account active',
    'Customer account',
    'Subscriptions',
    'Active subs',
    'Open-ended subs',
    'Latest sub end',
    'Customer invoices',
    'Multi-month invoices',
]


class Command(BaseCommand):
    help = (
        "Report on billing accounts that use (or have used) quarterly or "
        "yearly invoicing. Read-only."
    )

    def add_arguments(self, parser):
        parser.add_argument(
            '--csv',
            dest='csv_path',
            help="Also write the per-account summary to this path as CSV.",
        )

    def handle(self, csv_path=None, **options):
        accounts = list(get_non_monthly_accounts())
        multi_month_invoices = group_multi_month_customer_invoices()

        # Accounts with historical evidence but a monthly plan today.
        reverted_ids = set(multi_month_invoices) - {a.id for a in accounts}
        reverted_accounts = list(
            BillingAccount.objects.filter(id__in=reverted_ids).order_by('name')
        )

        all_accounts = accounts + reverted_accounts
        account_ids = [account.id for account in all_accounts]
        subscription_stats = get_subscription_stats(account_ids)
        invoice_stats = get_customer_invoice_stats(account_ids)

        def build_rows(accounts_subset):
            rows = []
            for account in accounts_subset:
                subs = subscription_stats.get(account.id, {})
                invoices = invoice_stats.get(account.id, {})
                rows.append([
                    account.id,
                    account.name,
                    account.invoicing_plan,
                    account.is_active,
                    account.is_customer_billing_account,
                    subs.get('subscriptions', 0),
                    subs.get('active', 0),
                    subs.get('open_ended', 0),
                    subs.get('latest_end'),
                    invoices.get('invoices', 0),
                    len(multi_month_invoices.get(account.id, [])),
                ])
            return rows

        current_rows = build_rows(accounts)
        reverted_rows = build_rows(reverted_accounts)

        self.stdout.write(
            "\nAccounts currently set to QUARTERLY or YEARLY invoicing\n"
            "=======================================================\n"
        )
        print_table(self.stdout, ACCOUNT_HEADERS, current_rows)

        self.stdout.write(
            "\nAccounts with multi-month customer invoices but a MONTHLY plan today\n"
            "===================================================================\n"
            "  (past use of quarterly/yearly invoicing, since reverted)\n"
        )
        print_table(self.stdout, ACCOUNT_HEADERS, reverted_rows)

        self.stdout.write(
            "\nMulti-month customer invoices\n"
            "=============================\n"
            "  (the historical records that would need preserving)\n"
        )
        invoice_rows = []
        for account in all_accounts:
            for invoice in multi_month_invoices.get(account.id, []):
                invoice_rows.append([
                    account.name,
                    invoice.invoice_number,
                    invoice.date_start,
                    invoice.date_end,
                    invoice.months_spanned,
                    invoice.balance,
                    invoice.is_hidden,
                    invoice.is_hidden_to_ops,
                ])
        print_table(self.stdout, [
            'Account',
            'Invoice',
            'Period start',
            'Period end',
            'Months',
            'Balance',
            'Hidden',
            'Hidden to ops',
        ], invoice_rows)

        self.stdout.write(
            "\nSubscriptions under accounts flagged above\n"
            "=========================================\n"
        )
        subscription_rows = [
            [
                subscription.account.name,
                subscription.account.invoicing_plan,
                subscription.id,
                subscription.subscriber.domain,
                subscription.plan_version.plan.name,
                subscription.service_type,
                subscription.is_active,
                subscription.date_start,
                subscription.date_end,
                subscription.do_not_invoice,
            ]
            for subscription in (
                Subscription.visible_and_suppressed_objects
                .filter(account_id__in=account_ids)
                .select_related('account', 'subscriber', 'plan_version__plan')
                .order_by('account__name', '-date_start')
            )
        ]
        print_table(self.stdout, [
            'Account',
            'Invoicing plan',
            'Sub ID',
            'Domain',
            'Software plan',
            'Type',
            'Active',
            'Start',
            'End',
            'Do not invoice',
        ], subscription_rows)

        self.stdout.write("\nSummary\n=======\n")
        for plan, _ in InvoicingPlan.CHOICES:
            count = BillingAccount.objects.filter(invoicing_plan=plan).count()
            customer_count = BillingAccount.objects.filter(
                invoicing_plan=plan, is_customer_billing_account=True
            ).count()
            active_count = BillingAccount.objects.filter(
                invoicing_plan=plan, is_active=True
            ).count()
            self.stdout.write(
                f"  {plan}: {count} accounts "
                f"({active_count} active, {customer_count} customer billing)\n"
            )
        self.stdout.write(
            f"  Multi-month customer invoices: {len(invoice_rows)} "
            f"across {len(multi_month_invoices)} accounts\n"
        )
        # Non-customer invoices ignore invoicing_plan entirely, so any that
        # bill more than one month came from somewhere else. Reported as a
        # sanity check on the assumption above.
        stray = get_multi_month_invoices(Invoice.api_objects.all()).count()
        self.stdout.write(
            f"  Multi-month subscription (non-customer) invoices: {stray}\n"
        )

        if csv_path:
            with open(csv_path, 'w', newline='') as csv_file:
                writer = csv.writer(csv_file)
                writer.writerow(ACCOUNT_HEADERS)
                writer.writerows(current_rows + reverted_rows)
            self.stdout.write(f"\nPer-account summary written to {csv_path}\n")
