"""
Find and requeue Connect-bound repeat records rejected with a 403 while the
CloudFront WAF (SizeRestrictions_BODY) was blocking POSTs over 8KB to
connect.dimagi.com.

Block: 2026-10-15 18:00 -> ~2026-10-16 13:00 UTC, padded by 12h each side.

Usage, in ``./manage.py shell``: paste this file, then

    report()                       # counts, read-only
    sample_connect_403s()          # peek at non-CloudFront 403s
    requeue_cloudfront_blocks()    # dry run: shows what would be requeued
    requeue_cloudfront_blocks(dry_run=False)   # actually requeue
"""
from datetime import datetime, timezone

from django.db.models import Count, Exists, OuterRef

from corehq.motech.models import ConnectionSettings
from corehq.motech.repeaters.const import State
from corehq.motech.repeaters.models import (
    Repeater,
    RepeatRecord,
    RepeatRecordAttempt,
)

WINDOW_START = datetime(2026, 10, 15, 6, 0, tzinfo=timezone.utc)
WINDOW_END = datetime(2026, 10, 17, 1, 0, tzinfo=timezone.utc)
CONNECT_HOST = "connect.dimagi.com"
CLOUDFRONT_MARKER = "Generated by cloudfront"


def get_connect_repeater_ids():
    cs_ids = ConnectionSettings.objects.filter(
        url__contains=CONNECT_HOST,
    ).values_list("id", flat=True)
    return list(
        Repeater.objects.filter(connection_settings_id__in=list(cs_ids))
        .values_list("id", flat=True)
    )


def _rejected_403_attempts(cloudfront_only):
    attempts = RepeatRecordAttempt.objects.filter(
        repeat_record=OuterRef("pk"),
        state=State.PayloadRejected,
        created_at__gte=WINDOW_START,
        created_at__lt=WINDOW_END,
        message__contains="\n403: ",
    )
    if cloudfront_only:
        attempts = attempts.filter(message__contains=CLOUDFRONT_MARKER)
    return attempts


def get_403_records(cloudfront_only=False, repeater_ids=None):
    if repeater_ids is None:
        repeater_ids = get_connect_repeater_ids()
    return RepeatRecord.objects.filter(
        repeater_id__in=repeater_ids,
        state=State.PayloadRejected,
    ).filter(Exists(_rejected_403_attempts(cloudfront_only)))


def get_non_cloudfront_403_records(repeater_ids=None):
    return get_403_records(repeater_ids=repeater_ids).exclude(
        Exists(_rejected_403_attempts(cloudfront_only=True))
    )


def _by_domain(records):
    return list(records.values("domain").annotate(n=Count("id")).order_by("-n"))


def report():
    repeater_ids = get_connect_repeater_ids()
    all_403 = get_403_records(repeater_ids=repeater_ids)
    cloudfront_403 = get_403_records(cloudfront_only=True, repeater_ids=repeater_ids)
    connect_403 = get_non_cloudfront_403_records(repeater_ids=repeater_ids)

    n_all, n_cf = all_403.count(), cloudfront_403.count()
    print(f"Connect repeaters:         {len(repeater_ids)}")
    print(f"Window:                    {WINDOW_START} -> {WINDOW_END}")
    print(f"403s in window:            {n_all}")
    print(f"  CloudFront (WAF) blocks: {n_cf}")
    print(f"  other / genuine Connect: {n_all - n_cf}")
    print("\nCloudFront blocks by domain:")
    for row in _by_domain(cloudfront_403):
        print(f"  {row['domain']}: {row['n']}")
    print("\nOther 403s by domain:")
    for row in _by_domain(connect_403):
        print(f"  {row['domain']}: {row['n']}")


def sample_connect_403s(limit=5):
    """Print response messages of 403s that did not come from CloudFront."""
    records = get_non_cloudfront_403_records()[:limit]
    for record in records:
        attempt = record.attempt_set.filter(state=State.PayloadRejected).last()
        print(f"--- {record.domain} record={record.id} payload={record.payload_id}")
        print(attempt.message[:500] if attempt else "(no attempt)")


def requeue_cloudfront_blocks(dry_run=True):
    """
    Requeue records blocked by the CloudFront WAF. Only run with
    ``dry_run=False`` once the SizeRestrictions_BODY fix is deployed,
    otherwise they will be blocked again.
    """
    records = get_403_records(cloudfront_only=True)
    total = records.count()
    if dry_run:
        print(f"[dry run] would requeue {total} records:")
        for row in _by_domain(records):
            print(f"  {row['domain']}: {row['n']}")
        print("Call requeue_cloudfront_blocks(dry_run=False) to requeue.")
        return total

    requeued = 0
    for record in records.iterator():
        record.requeue()
        requeued += 1
        if requeued % 500 == 0:
            print(f"  requeued {requeued}/{total}")
    print(f"Requeued {requeued} records.")
    return requeued
